// §314 AI가 낸 액션 아이템을 태스크 줄로 다듬는다.
//
// 이 함수가 이 기능의 전부다. 모델이 무엇을 내놓든 문서에 들어가는 것은 여기를
// 지난 것뿐이므로, "무엇을 버리는가"가 "무엇을 남기는가"만큼 중요하다.
import { describe, expect, it } from "vitest";

import {
  ACTION_ITEM_SYSTEM_PROMPT,
  normalizeActionItems,
} from "../action-items";

/** 수요일. 요일 계산을 사람이 검산할 수 있게 고정한다. */
const WED = new Date(2026, 8, 16);

function norm(raw: string) {
  return normalizeActionItems(raw, WED);
}

describe("날짜 표현이 필드가 된다", () => {
  it("‼️ 상대 표현은 문서에 남지 않는다", () => {
    // `내일`을 그대로 두면 하루 뒤에 그 줄이 거짓말을 한다. 절대 날짜만 남는다.
    expect(norm("- [ ] 보고서 초안 내일")).toBe(
      "- [ ] 보고서 초안 📅2026-09-17",
    );
  });

  it.each([
    ["- [ ] 검토 금요일까지", "- [ ] 검토 📅2026-09-18"],
    ["- [ ] 발송 다음 주 월요일", "- [ ] 발송 📅2026-09-28"],
    ["- [ ] Draft the deck by friday", "- [ ] Draft the deck 📅2026-09-18"],
    ["- [ ] Ship it in 3 days", "- [ ] Ship it 📅2026-09-19"],
    ["- [ ] 결산 9월 30일", "- [ ] 결산 📅2026-09-30"],
  ])("%s → %s", (raw, want) => {
    expect(norm(raw)).toBe(want);
  });

  it("‼️ 이미 필드가 있는 줄에서 갈아끼워도 공백이 남지 않는다", () => {
    // 원문에 이미 `📅`가 있고 뒤에 말로 적은 날짜가 또 있는 경우. 표현을 떼면서 앞
    // 공백을 함께 가져가지 않으면 교체 경로에서는 아무도 그것을 치워 주지 않는다
    // (삽입 경로는 줄 끝 공백을 털지만, 교체는 자리만 바꾼다).
    expect(norm("- [ ] 보고서 📅2026-01-01 내일")).toBe(
      "- [ ] 보고서 📅2026-09-17",
    );
  });

  it("날짜가 없으면 본문 그대로다", () => {
    expect(norm("- [ ] 회의실 예약")).toBe("- [ ] 회의실 예약");
  });

  it("‼️ 줄 가운데의 날짜 표현은 건드리지 않는다", () => {
    // 끝이 아닌 자리의 `내일`은 문장의 일부다 — 떼어내면 뜻이 무너진다.
    expect(norm("- [ ] 내일 일정 정리해서 공유")).toBe(
      "- [ ] 내일 일정 정리해서 공유",
    );
  });

  it("‼️ 사람 이름은 본문에 남는다 — 담당자 필드를 만들지 않는다", () => {
    expect(norm("- [ ] 김철수에게 확인 요청 내일")).toBe(
      "- [ ] 김철수에게 확인 요청 📅2026-09-17",
    );
  });
});

describe("‼️ 목록 항목이 아닌 줄은 버린다", () => {
  it("머리말과 맺음말이 문서에 들어가지 않는다", () => {
    // 그대로 두면 사용자가 자기가 쓰지 않은 문장을 회의록에서 보게 된다.
    const raw = [
      "다음은 회의에서 나온 액션 아이템입니다:",
      "",
      "- [ ] 보고서 초안 내일",
      "- [ ] 예산 확인",
      "",
      "이상입니다. 더 필요한 것이 있으면 알려주세요.",
    ].join("\n");
    expect(norm(raw)).toBe("- [ ] 보고서 초안 📅2026-09-17\n- [ ] 예산 확인");
  });

  it("빈 알맹이는 버린다", () => {
    expect(norm("- [ ] \n-\n- [ ] 실제 할 일")).toBe("- [ ] 실제 할 일");
  });

  it("아무것도 없으면 빈 문자열", () => {
    expect(norm("이 글에는 액션 아이템이 없습니다.")).toBe("");
    expect(norm("")).toBe("");
  });
});

describe("형식을 어긴 출력도 받는다", () => {
  it("‼️ 불릿·번호도 태스크가 된다", () => {
    // 프롬프트는 체크박스를 요구하지만 모델은 자주 어긴다. 그때 결과가 통째로 비면
    // 사용자에게는 "못 찾았다"로 보이는데, 형식을 어긴 것과 못 찾은 것은 다른 사실이다.
    expect(norm("* 예산 확인\n1. 발송 내일\n+ 회의록 정리")).toBe(
      "- [ ] 예산 확인\n- [ ] 발송 📅2026-09-17\n- [ ] 회의록 정리",
    );
  });

  it("이미 체크된 항목도 열린 태스크로 낸다", () => {
    // 추출은 앞으로 할 일을 뽑는 것이다. 모델이 `[x]`를 내놓아도 그것은 형식 실수다.
    expect(norm("- [x] 예산 확인")).toBe("- [ ] 예산 확인");
  });

  it("굵은 글씨 껍데기를 벗긴다", () => {
    expect(norm("- [ ] **예산 확인**")).toBe("- [ ] 예산 확인");
    expect(norm("- [ ] __예산 확인__")).toBe("- [ ] 예산 확인");
  });

  it("본문 안의 강조는 남긴다", () => {
    expect(norm("- [ ] **긴급** 예산 확인")).toBe("- [ ] **긴급** 예산 확인");
  });

  it("들여쓰기는 지킨다 — 모델이 중첩을 내면 그 구조가 뜻이다", () => {
    expect(norm("- [ ] 상위\n  - [ ] 하위 내일")).toBe(
      "- [ ] 상위\n  - [ ] 하위 📅2026-09-17",
    );
  });
});

describe("프롬프트", () => {
  it("‼️ 날짜를 모델이 계산하지 말라고 못 박는다", () => {
    // 못 박지 않으면 모델이 `📅2026-09-17`을 지어내고, 그 날짜는 자주 틀린다.
    expect(ACTION_ITEM_SYSTEM_PROMPT).toContain("Do NOT convert it");
  });

  it("담당자 필드가 없다고 알린다", () => {
    expect(ACTION_ITEM_SYSTEM_PROMPT).toContain("no assignee field");
  });

  it("찾은 것이 없으면 아무것도 내지 말라고 한다", () => {
    expect(ACTION_ITEM_SYSTEM_PROMPT).toContain("output nothing");
  });
});
