// §306/§307 `[[…]]` 원문 하나가 **무엇을 가리키는가**.
//
// 인덱스는 위키링크 안쪽을 원문 그대로 담는다(§18.18-5). 그 원문을 대상으로 읽는 자가
// 둘 있다 — 노트별 섹션(§307 A)이 "이 노트인가"를 묻고, 아젠다의 링크 필터(§306)가
// "같은 대상인가"로 묶는다. 둘이 각자 벗기면 별칭 붙은 링크가 한쪽에서만 걸리고,
// 사용자는 필터에는 뜨는데 노트에서는 안 보이는 태스크를 만나게 된다.

import { basename } from "../path-utils";

/**
 * 별칭·앵커·폴더·확장자를 벗긴 링크 대상. 가리키는 것이 없으면 빈 문자열이다
 * (`[[#제목]]` 같은 같은 파일 안 앵커가 그렇다).
 */
export function linkTarget(raw: string): string {
  return basename(raw.split("|")[0].split("#")[0].split("^")[0].trim()).replace(
    /\.(md|markdown)$/i,
    "",
  );
}
