// §56m 에디터가 인정하는 `#tag`의 글자 어휘 — 입력 규칙과 라운드트립의 **공통 출처**.
//
// 이 파일이 생긴 이유: 같은 정규식이 두 벌 적혀 있었다. `tag-node.ts`의 입력 규칙(치는
// 순간 태그 노드를 만든다)과 `tag-transformer.ts`의 `TAG_NODE_RE`(파일을 읽어 태그 노드를
// 만든다)가 서로를 모른 채 같은 문자열을 각자 갖고 있었으므로, 한쪽만 넓히면 **친 것과 연
// 것이 달라 보이는** 상태가 된다. 이제 둘 다 여기서 만든다.
//
// ‼️ 남은 갈림 하나(의도적, dev/backlog.md에 기록): 여기 `\w`는 JavaScript 기준이라
// ASCII 뿐이고, 그래서 한글 음절 범위를 손으로 더한다. Rust 인덱서(`md/mod.rs`의
// `INLINE_TAG_RE`)의 `\w`는 `regex` 크레이트 기준이라 **유니코드 전체**의 문자를 포함한다.
// 결과: `#日本語`·`#café`는 태그 패널에는 뜨지만 에디터에서는 일반 텍스트로 보인다.
// 하이픈과 달리 이쪽을 넓히는 것은 CJK 문서의 렌더가 바뀌는 결정이라 따로 판단한다.

/**
 * 태그 한 마디에 쓸 수 있는 글자. 하이픈은 **맨 뒤**에 둔다 — 문자 클래스 안에서
 * 마지막 자리의 `-`만이 범위 기호가 아니라 글자 그대로다.
 *
 * 하이픈이 여기 있는 것이 계약이다. 없으면 인덱서는 `#someday-maybe`를 `someday`로
 * 읽는데 쓰는 쪽(`task/tag.rs`의 `is_tag_char`)은 하이픈까지 태그로 보아, 아젠다의
 * "미룸 해제"가 지울 대상을 못 찾고 조용히 아무 일도 하지 않았다.
 */
export const TAG_SEGMENT = "[\\w\\uAC00-\\uD7A3-]+";

/** `parent/child/grandchild` 중첩까지 포함한 태그 이름 전체. */
export const TAG_BODY = `${TAG_SEGMENT}(?:/${TAG_SEGMENT})*`;
